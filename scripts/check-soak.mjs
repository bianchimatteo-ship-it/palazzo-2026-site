// A long career played by the code, not by hand: 104 consecutive weeks on the real engine, with every kind of play mixed together — the decisions of the agenda, the weekly activities, the animated scenes
// (played by hand with seeded choices and simulated), the guest spots, the campaigns when the candidacies open, the votes of the assemblies, the language switched again and again — checkpoints at weeks 25, 50,
